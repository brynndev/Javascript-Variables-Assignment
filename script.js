// Global variable
let name = "Brynn";

// Block variable
{
    let age = 28;
    console.log(age);
}

// Mathematical operations
let num1 = 10;
let num2 = 5;

console.log(num1 + num2);
console.log(num1 - num2);
console.log(num1 * num2);
console.log(num1 / num2);

// String variable
let favoriteColor = "Pink"; // This is my favorite color
console.log(favoriteColor);

// Object variable using const
const person = {
    name: "Brynn",
    age: 28,
    favoriteColor: "Pink"
};

// Log the global variable
console.log(name);

// Log the object
console.log(person);